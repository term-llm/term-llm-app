async (page) => {
  const assert=(value,message)=>{if(!value)throw new Error(message)};
  const root=page.locator('[data-phone="5"]');
  const state=()=>page.evaluate(()=>JSON.parse(JSON.stringify(window.mediaHeaderPrototype.state[5])));
  const tab=name=>root.locator(`.bottom-nav [data-action="view:${name}"]`);
  const labels=await root.locator('.bottom-nav button').allTextContents();
  assert(JSON.stringify(labels)===JSON.stringify(['Agents','Chat','Music','Podcasts']),'Four labelled tabs use Agents terminology');
  assert(!(await root.innerText()).includes('Nodes'),'No user-facing Nodes label remains');
  assert(await root.locator('.app-header').count()===1,'Agents has an app header');
  assert(await root.locator('.agent-chat-header').count()===0,'Agent web header is not duplicated on the browser screen');
  const audio=(await state()).media;
  const footerBefore=await root.locator('.bottom-nav').boundingBox();
  await root.screenshot({path:'output/playwright/header-concepts/media/selected/agents-podcast.png'});
  await root.locator('.node').first().click();
  assert(await root.locator('.app-header').count()===0,'Chat removes the app header, rather than merely hiding its controls');
  assert(await root.locator('.agent-chat-header').count()===1,'Chat has exactly one agent-owned header');
  assert(await root.locator('.app-header [data-action="settings"]').count()===0,'No app Settings gear is layered over agent chat');
  const status=await root.locator('.statusbar').boundingBox();
  const agent=await root.locator('.agent-chat-header').boundingBox();
  assert(Math.abs(agent.y-(status.y+status.height))<1,'No blank app-header spacer above the agent header');
  const footerAfter=await root.locator('.bottom-nav').boundingBox();
  assert(Math.abs(footerAfter.y-footerBefore.y)<1,'Bottom navigation stays anchored while chat changes header ownership');
  await root.getByRole('textbox',{name:'Draft message'}).fill('Keep this draft while I browse music.');
  assert((await state()).media.kind===audio.kind&&(await state()).media.position===audio.position,'Entering chat does not change playback');
  await root.screenshot({path:'output/playwright/header-concepts/media/selected/chat-podcast.png'});
  await tab('Music').click();
  assert(await root.locator('.app-header').count()===1,'Music restores its contextual app header');
  assert(await root.locator('.agent-chat-header').count()===0,'Agent web chrome is chat-only');
  assert((await state()).media.kind==='podcast'&&(await state()).media.playing,'Music browsing keeps the podcast playing');
  await tab('Chat').click();
  assert(await root.getByRole('textbox',{name:'Draft message'}).inputValue()==='Keep this draft while I browse music.','Draft survives tab changes');
  assert(await root.locator('.app-header').count()===0,'Returning to Chat still has no app header');
  await root.locator('.player-strip [data-action="toggle"]').click();
  assert(!(await state()).media.playing,'Pause works from chat without an app header');
  await root.locator('.player-strip [data-action="toggle"]').click();
  await page.getByRole('button',{name:'Idle',exact:true}).click();
  assert(await root.locator('.media-footer').count()===0,'No idle mini-player takes space from chat');
  assert(await root.locator('.app-header').count()===0,'Idle Chat is also headerless at app level');
  await root.screenshot({path:'output/playwright/header-concepts/media/selected/chat-idle.png'});
  await tab('Agents').click();
  assert(await root.getByRole('heading',{name:'Agents',exact:true}).count()===0,'Agents label is contextual chrome, not a duplicate body heading');
  assert(await root.locator('.app-header .title').textContent()==='Agents','Default screen is Agents');
  await root.screenshot({path:'output/playwright/header-concepts/media/selected/agents-idle.png'});
  await page.getByRole('button',{name:'Podcast playing',exact:true}).click();
  await page.screenshot({path:'output/playwright/header-concepts/media/selected/interactive-refinement.png',fullPage:true});
  return {result:'PASS',concept:5,checks:['Agents terminology','one app header on browsing screens','only the agent-owned header in Chat','no blank header spacer','anchored bottom tabs','retained chat draft','independent persistent playback','idle player absent'],note:'Prototype only; agent header is illustrative web content, not a pixel-exact capture of a live agent'};
}
