#!/usr/bin/env python3
"""Offline check that term-llm ships its own MIT license and the pinned
third-party notices in every distributed bundle. No network, no Xcode build.
Needs macOS `plutil` to read project.pbxproj.

Licenses/THIRD-PARTY-NOTICES.txt is generated from the license texts recorded
in Licenses/SOURCES.json and ships inside each app bundle, so a text edit, a
dependency bump or a hand edit of the notices fails this check instead of
shipping stale or partial attribution.

  python3 scripts/check-license-notices.py                 # verify
  python3 scripts/check-license-notices.py --write         # regenerate notices
  python3 scripts/check-license-notices.py --bundle <app>  # also check a built
                                                           # .app (repeatable)
"""
import argparse
import hashlib
import json
import pathlib
import posixpath
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
LICENSES = ROOT / "Licenses"
NOTICES_NAME = "THIRD-PARTY-NOTICES.txt"
NOTICES = LICENSES / NOTICES_NAME
SOURCES = LICENSES / "SOURCES.json"
SUMMARY = ROOT / "THIRD-PARTY-NOTICES.md"
PROJECT = ROOT / "TermLLM.xcodeproj/project.pbxproj"
PACKAGE_RESOLVED = ROOT / "TermLLM.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved"
WEBRTC_CHECKOUT = ROOT / "DerivedData/SourcePackages/checkouts/WebRTC/Package.swift"
# Targets a user receives. The notification extensions are nested inside these
# bundles, and term-llm-computer is a bare tool inside the Mac app (a tool
# target has no bundle for resources), so the enclosing app's copy covers both.
RESOURCE_TARGETS = ("TermLLM", "TermLLMMac", "TermLLMComputerUse")
REQUIRED_RESOURCES = ("LICENSE", "Licenses/" + NOTICES_NAME)
SEPARATOR, WIDTH = "=" * 80, 78
PREAMBLE = """\
term-llm third-party notices
============================

term-llm is Copyright (c) 2026 Sam Saffron and is distributed under the MIT
License. term-llm builds also contain the third-party components below. Each
license text is reproduced verbatim from the pinned source recorded for it in
Licenses/SOURCES.json, which holds the revisions, URLs and digests.

This file ships as THIRD-PARTY-NOTICES.txt in the root of term-llm.app (iOS)
and in term-llm.app/Contents/Resources (macOS), next to LICENSE, and in
"term-llm Computer Use.app/Contents/Resources". term-llm-computer is
distributed inside term-llm.app/Contents/Helpers and has no bundle of its own,
so the notices travel with the app bundle that contains it. The source copy
lives in Licenses/.

Generated by scripts/check-license-notices.py --write. Edit the license texts
or Licenses/SOURCES.json instead of this file.
"""


class CheckError(Exception):
    """The inputs cannot be checked at all (missing or malformed files)."""


def digest(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def read_json(path):
    try:
        return json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise CheckError(f"cannot read {pathlib.Path(path).name}: {error}")


def load_sources():
    sources = read_json(SOURCES)
    components = sources.get("components")
    if not components:
        raise CheckError(f"{SOURCES.relative_to(ROOT)} has no components")
    for component in components:
        for key in ("id", "name", "license", "source", "licenseFile", "sha256", "products"):
            if not component.get(key):
                raise CheckError(f"{SOURCES.relative_to(ROOT)}: component missing {key}: {component!r}")
    return sources


def _field(label, values):
    """A notice field with comma-separated values wrapped at WIDTH columns."""
    prefix = label + ": "
    lines, current = [], prefix
    for index, value in enumerate(values):
        piece = value + ("," if index < len(values) - 1 else "")
        if len(current) + len(piece) <= WIDTH or current == prefix:
            current += piece + " "
        else:
            lines.append(current.rstrip())
            current = " " * len(prefix) + piece + " "
    lines.append(current.rstrip())
    return "\n".join(lines)


def _section(component, text):
    heading = component["name"] + (" " + component["version"] if component.get("version") else "")
    lines = [SEPARATOR, heading, component["license"], _field("Source", [component["source"]])]
    if component.get("revision"):
        lines.append(_field("Pinned", [component["revision"]]))
    if component.get("artifact"):
        lines.append(_field("Artifact", [component["artifact"]["url"]]))
        lines.append(_field("Artifact sha256", [component["artifact"]["checksum"]]))
    if component.get("note"):
        lines.append(_field("Note", [component["note"]]))
    lines.append(_field("Included in", component["products"]))
    lines.append(SEPARATOR)
    return "\n".join(lines) + "\n" + text.rstrip("\n")


def render(sources):
    """The exact contents of THIRD-PARTY-NOTICES.txt for these sources."""
    blocks = [PREAMBLE.rstrip("\n")]
    for component in sources["components"]:
        text = (ROOT / component["licenseFile"]).read_text(encoding="utf-8")
        blocks.append(_section(component, text))
    return "\n\n".join(blocks).rstrip("\n") + "\n"


def check_licenses(sources):
    """Recorded texts are unchanged and no file in Licenses/ is orphaned."""
    problems, referenced = [], set()
    for component in sources["components"]:
        path = ROOT / component["licenseFile"]
        referenced.add(posixpath.normpath(component["licenseFile"]))
        if not path.is_file():
            problems.append(f"missing license text {component['licenseFile']} for {component['name']}")
        elif digest(path) != component["sha256"]:
            problems.append(f"{component['licenseFile']} no longer matches the recorded sha256 for "
                            f"{component['name']}; re-copy the pinned text and update SOURCES.json")
    for path in sorted(LICENSES.iterdir()):
        relative = posixpath.normpath(str(path.relative_to(ROOT)))
        if path.name in ("README.md", "SOURCES.json", NOTICES_NAME, ".DS_Store") or relative in referenced:
            continue
        problems.append(f"{relative} is not referenced by SOURCES.json; record it or delete it")
    return problems


def check_packages(sources):
    """Swift package pins still match the recorded revisions and notices."""
    pins = {pin["identity"]: pin.get("state", {}) for pin in read_json(PACKAGE_RESOLVED).get("pins", [])}
    recorded = {component["packageIdentity"]: component for component in sources["components"]
                if component.get("packageIdentity")}
    problems = []
    for identity in sorted(set(pins) - set(recorded)):
        problems.append(f"{identity} is pinned in Package.resolved but has no notice in SOURCES.json")
    for identity, component in sorted(recorded.items()):
        pin = pins.get(identity)
        if pin is None:
            problems.append(f"{component['name']} is recorded but no longer pinned; drop its notice")
            continue
        if component.get("revision") and pin.get("revision") != component["revision"]:
            problems.append(f"{component['name']}: pinned revision {pin.get('revision')} is not the "
                            f"recorded {component['revision']}; refresh its notice")
        if component.get("version") and pin.get("version") and pin["version"] != component["version"]:
            problems.append(f"{component['name']}: pinned version {pin['version']} is not the "
                            f"recorded {component['version']}; refresh its notice")
    return problems


def check_artifact(sources):
    """Tie the linked WebRTC binary to the artifact its notice came from."""
    component = next((item for item in sources["components"] if item.get("artifact")), None)
    if component is None or not WEBRTC_CHECKOUT.is_file():
        return []
    resolved = WEBRTC_CHECKOUT.read_text(encoding="utf-8")
    return [f"{WEBRTC_CHECKOUT.relative_to(ROOT)}: binary target does not match the recorded "
            f"{component['name']} artifact ({key})"
            for key in ("url", "checksum") if component["artifact"][key] not in resolved]


def check_notices(sources):
    try:
        actual = NOTICES.read_text(encoding="utf-8")
    except OSError as error:
        return [f"cannot read {NOTICES.relative_to(ROOT)}: {error}"]
    if actual == render(sources):
        return []
    return [f"{NOTICES.relative_to(ROOT)} is not what rendering SOURCES.json produces; "
            f"run --write and review the diff"]


def check_summary(sources):
    """The repository summary must point at every shipped text."""
    try:
        text = SUMMARY.read_text(encoding="utf-8").lower()
    except OSError as error:
        return [f"cannot read {SUMMARY.name}: {error}"]
    problems = [f"{SUMMARY.name} does not mention {component['name']}"
                for component in sources["components"]
                if component["name"].lower() not in text]
    problems += [f"{SUMMARY.name} does not link {component['licenseFile']}"
                 for component in sources["components"]
                 if posixpath.normpath(component["licenseFile"]).lower() not in text]
    if ("licenses/" + NOTICES_NAME).lower() not in text:
        problems.append(f"{SUMMARY.name} does not point at Licenses/{NOTICES_NAME}")
    return problems


def load_project():
    try:
        result = subprocess.run(["plutil", "-convert", "json", "-o", "-", str(PROJECT)],
                                capture_output=True, text=True, check=True)
        project = json.loads(result.stdout)
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError) as error:
        raise CheckError(f"cannot parse {PROJECT.relative_to(ROOT)} with plutil: {error}")
    if not isinstance(project, dict) or not isinstance(project.get("objects"), dict):
        raise CheckError(f"{PROJECT.relative_to(ROOT)} has no objects table")
    return project


def file_paths(project):
    """File reference ID -> repository-relative path, resolving group paths."""
    objects, paths = project["objects"], {}

    def walk(group_id, base):
        group = objects[group_id]
        base = posixpath.join(base, group.get("path", ""))
        for child_id in group.get("children", []):
            child = objects[child_id]
            if child.get("isa") in ("PBXGroup", "PBXVariantGroup", "XCVersionGroup"):
                walk(child_id, base)
            elif child.get("isa") == "PBXFileReference":
                tree, path = child.get("sourceTree", "<group>"), child.get("path") or child.get("name", "")
                if tree == "<group>":
                    paths[child_id] = posixpath.normpath(posixpath.join(base, path))
                elif tree == "SOURCE_ROOT":
                    paths[child_id] = posixpath.normpath(path)

    walk(objects[project["rootObject"]]["mainGroup"], "")
    return paths


def shipped_resources(project, target_name):
    """Repository paths a target copies into its Resources build phase."""
    objects = project["objects"]
    targets = [item for item in objects.values()
               if item.get("isa") == "PBXNativeTarget" and item.get("name") == target_name]
    if len(targets) != 1:
        raise CheckError(f"expected one {target_name} target, found {len(targets)}")
    paths, shipped = file_paths(project), set()
    for phase_id in targets[0].get("buildPhases", []):
        if objects[phase_id].get("isa") != "PBXResourcesBuildPhase":
            continue
        for build_id in objects[phase_id].get("files", []):
            reference = objects[build_id].get("fileRef")
            shipped.add(paths.get(reference))
    return shipped


def check_project():
    project, problems = load_project(), []
    for target in RESOURCE_TARGETS:
        shipped = shipped_resources(project, target)
        for expected in REQUIRED_RESOURCES:
            if expected not in shipped:
                problems.append(f"{target}: {expected} is not in the target's Resources build phase")
            elif not (ROOT / expected).is_file():
                problems.append(f"{target}: resource path {expected} does not exist")
    return problems


def bundle_problems(bundle):
    """A built .app must carry the same two files this checkout ships."""
    bundle, problems = pathlib.Path(bundle), []
    if not bundle.is_dir():
        return [f"{bundle}: not a directory"]
    for resource in REQUIRED_RESOURCES:
        candidates = [bundle / resource.split("/")[-1], bundle / "Contents/Resources" / resource.split("/")[-1]]
        found = next((path for path in candidates if path.is_file()), None)
        if found is None:
            problems.append(f"{bundle}: {candidates[0].name} is missing from {bundle} and Contents/Resources")
        elif found.read_bytes() != (ROOT / resource).read_bytes():
            problems.append(f"{found}: differs from {resource} in this checkout")
    return problems


def verify(bundles=()):
    sources = load_sources()
    problems = check_licenses(sources)
    if not problems:
        problems = check_artifact(sources) + check_notices(sources)
    problems += check_summary(sources) + check_packages(sources) + check_project()
    for bundle in bundles:
        problems += bundle_problems(bundle)
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true",
                        help=f"regenerate Licenses/{NOTICES_NAME} from the recorded texts")
    parser.add_argument("--bundle", action="append", default=[], metavar="APP",
                        help="also check a built .app bundle (repeatable)")
    arguments = parser.parse_args(argv)
    try:
        if arguments.write:
            NOTICES.write_text(render(load_sources()), encoding="utf-8")
            print(f"wrote {NOTICES.relative_to(ROOT)}")
        problems = verify(arguments.bundle)
    except CheckError as error:
        print(f"licenses: {error}", file=sys.stderr)
        return 2
    for problem in problems:
        print(f"licenses: {problem}", file=sys.stderr)
    if problems:
        return 1
    print(f"licenses: ok ({len(REQUIRED_RESOURCES)} resources in {len(RESOURCE_TARGETS)} targets, "
          f"{len(load_sources()['components'])} components)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
